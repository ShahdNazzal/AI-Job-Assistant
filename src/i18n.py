def available_languages() -> dict[str, str]:
    """Return ``{code: display_name}`` for the language selector."""
    return dict(_LANGUAGES)


def is_rtl_language(lang: str) -> bool:
    return lang in _RTL_LANGUAGES


def translate(key: str, lang: str | None = None, **kwargs: Any) -> str:
    """Translate ``key`` into ``lang`` (default: English), formatting kwargs."""
    table = TRANSLATIONS.get(lang or _DEFAULT_LANG) or TRANSLATIONS[_DEFAULT_LANG]
    text = table.get(key) or TRANSLATIONS[_DEFAULT_LANG].get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def rtl_wrap(text: str, lang: str) -> str:
    """Wrap HTML/markdown text in a RTL container when ``lang`` is RTL."""
    if is_rtl_language(lang):
        return f'<div dir="rtl" style="text-align:right">{text}</div>'
    return text


